#!/usr/bin/env python3
"""Imhotep - write docs/provenance/ported.md: every ported function of Pharaoh.exe, from the port
tables (build/state_run --list) and the source (the file holding its table entry).

Copyright (C) 2026 Imhotep contributors. Licensed under the GNU AGPL-3.0.

  python3 tools/gen/gen_ported_index.py [BUILD_DIR]
"""
import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
KIND = {'0': '', '1': 'partial', '2': 'platform request'}


def main():
    build = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, 'build')
    out = subprocess.run([os.path.join(build, 'state_run'), '--list'], capture_output=True, text=True,
                         check=True).stdout
    where = {}
    for d, _, files in os.walk(os.path.join(ROOT, 'core')):
        for f in files:
            if not f.endswith('.c'):
                continue
            path = os.path.join(d, f)
            for m in re.finditer(r'\{\s*(0x[0-9A-Fa-f]{8})u?,\s*"', open(path).read()):
                where.setdefault(int(m.group(1), 16), os.path.relpath(path, ROOT))
    rows = []
    for line in out.splitlines():
        a, nargs, bits, this, kind, name = line.split(None, 5)
        addr = int(a, 16)
        notes = [KIND.get(kind, kind)] if KIND.get(kind) else []
        if int(this, 16):
            notes.append('this = %s' % this)
        if '(in ' in name or name.endswith(')'):
            notes.append('inside its caller')
        rows.append((addr, name, where.get(addr, '?'), ', '.join(notes)))
    rows.sort()
    lines = ['# Ported functions', '',
             'Generated by `tools/gen/gen_ported_index.py` from the port tables (core/state/ported.h); do not',
             'edit. Every entry is checked against the original by the function harness and the tick',
             'lockstep (docs/porting.md, tests/differential/README.md). Hand-written notes on the',
             'functions read so far: README.md.', '',
             '%d functions.' % len(rows), '',
             '| Address | Port | File | Notes |', '|---|---|---|---|']
    lines += ['| 0x%08X | `%s` | %s | %s |' % r for r in rows]
    open(os.path.join(ROOT, 'docs', 'provenance', 'ported.md'), 'w').write('\n'.join(lines) + '\n')
    print('%d functions' % len(rows))
    return 0


if __name__ == '__main__':
    sys.exit(main())
