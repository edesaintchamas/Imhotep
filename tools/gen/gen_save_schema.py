"""Write the saved-game schema of the reference Pharaoh.exe (the layout it loads into) as C.

  python3 tools/gen/gen_save_schema.py   # reads $IMHOTEP_GAME_DIR/Pharaoh.exe

Records 0-146 are the static table at 0x005E09A0 (20 bytes: compressed, variable address,
element size, element count, converter list). Records 147-180 are zero in the static data and
filled at run time by the initialiser at 0x004D1350; their values are listed below as read from
its disassembly (docs/formats/save.md §3). Converter lists are summarised by the version below
which they apply (entry +8, @bin 0x004D0E10). Checks the executable's SHA-256 first.
"""
import hashlib, json, os, struct, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
GAME_DIR = Path(os.environ.get("IMHOTEP_GAME_DIR", ROOT / "local" / "game" / "app"))
OUT = ROOT / "core" / "io" / "save_schema.c"
STATIC_VA, STATIC_COUNT, TOTAL = 0x005E09A0, 147, 181

# @bin 0x004D1350 run-time records: (compressed, address, element size, count). Record 147's
# compression flag is stored outside the initialiser's range; taken from the version-160 records.
RUNTIME = [
    (1, 0x00D38360, 36, 1), (1, 0x00978D9C, 4, 51984), (0, 0x005C1350, 24, 13),
    *[(0, 0x00D0568C - 4 * k, 4, 1) for k in range(16)],          # 150-165
    (0, 0x007027B8, 1, 26), (0, 0x006FDC88, 1, 15), (1, 0x00A9010C, 1, 51984),
    (0, 0x007027B4, 1, 1), (1, 0x00A509BC, 1, 51984), (0, 0x005E45B0, 24, 10),
    (0, 0x005E46A0, 24, 18), (0, 0x0078D798, 4, 1), (0, 0x00E39080, 4, 1),
    (0, 0x006FDCE0, 12, 1), (0, 0x005C1F80, 24, 27), (0, 0x005C1488, 24, 27),
    (0, 0x005C1E18, 24, 15), (0, 0x005C2208, 24, 56), (0, 0x005C1710, 24, 75),
]


def va2off(va: int) -> int:
    if 0x576000 <= va < 0x606000:          # .data
        return va - 0x576000 + 0x176000
    if 0x56F000 <= va < 0x576000:          # .rdata
        return va - 0x56F000 + 0x16F000
    raise ValueError(hex(va))


def main() -> None:
    exe = (GAME_DIR / "Pharaoh.exe").read_bytes()
    record = json.loads((ROOT / "docs" / "source-fingerprint.json").read_text())["files"]
    if hashlib.sha256(exe).hexdigest() != record.get("Pharaoh.exe"):
        sys.exit("Pharaoh.exe does not match the reference fingerprint")
    assert len(RUNTIME) == TOTAL - STATIC_COUNT
    rows = []
    for i in range(STATIC_COUNT):
        comp, addr, size, count, conv = struct.unpack_from("<5I", exe, va2off(STATIC_VA) + 20 * i)
        below = 0
        if conv:   # first entry's version threshold (+8); lists are terminated by a 0 threshold
            below = struct.unpack_from("<I", exe, va2off(conv) + 8)[0]
            assert struct.unpack_from("<I", exe, va2off(conv) + 16 + 8)[0] == 0, "one entry expected"
        rows.append((comp, addr, size, count, below))
    rows += [(c, a, s, n, 0) for c, a, s, n in RUNTIME]
    lines = [
        "/* Generated by tools/gen/gen_save_schema.py from the reference Pharaoh.exe (GOG 2.1,",
        " * docs/source-fingerprint.json). Do not edit. Licensed under the GNU AGPL-3.0. */",
        '#include "io/save_schema.h"',
        "",
        "/* @bin 0x005E09A0 records 0-146 (static), @bin 0x004D1350 records 147-180 (run time).",
        " * {compressed, variable address, element size, element count, converter below version} */",
        "const save_schema_record save_schema[SAVE_SCHEMA_RECORDS] = {",
    ]
    for i, (c, a, s, n, b) in enumerate(rows):
        lines.append(f"    {{{c}, 0x{a:08X}u, {s}, {n}, {b}}}, /* {i} */")
    lines += ["};", ""]
    OUT.write_text("\n".join(lines))
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
