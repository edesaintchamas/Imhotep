#!/usr/bin/env python3
"""Imhotep - write core/state/functions.h: a named constant for every ported function of Pharaoh.exe,
from the port tables in core/ and present/ (`{0x00XXXXXXu, "name", ...}` rows), for the targets of
GAME_CALL / GAME_CALLT and the other places code names an original function by its address
(docs/naming.md).

Copyright (C) 2026 Imhotep contributors. Licensed under the GNU AGPL-3.0.

  python3 tools/gen/gen_functions.py

FN_<NAME>: the port's name in upper case (parenthesised notes and anything that is not a letter or a
digit dropped). Names that two addresses share get the address appended. Functions without a port
(docs/provenance/frontier.md) are not listed: code names them by address until they get one.
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
ROW = re.compile(r'\{\s*(0x[0-9A-Fa-f]{8})u?,\s*"([^"]*)"')


def ident(name):
    name = re.sub(r'\([^)]*\)', ' ', name)
    name = re.sub(r'[^0-9A-Za-z]+', '_', name).strip('_').upper()
    return name or 'UNNAMED'


def main():
    found = {}
    for top in ('core', 'present'):
        for d, _, files in sorted(os.walk(os.path.join(ROOT, top))):
            for f in sorted(files):
                if not f.endswith('.c'):
                    continue
                path = os.path.join(d, f)
                for m in ROW.finditer(open(path).read()):
                    a = int(m.group(1), 16)
                    if a >= 0x0056F000:  # data, not code (should not happen)
                        continue
                    found.setdefault(a, (m.group(2), os.path.relpath(path, ROOT)))
    by_name = {}
    for a, (n, _) in found.items():
        by_name.setdefault(ident(n), []).append(a)
    lines = ['/* Imhotep - the original functions by name: generated by tools/gen/gen_functions.py from the',
             ' * port tables (core/state/ported.h); do not edit. Copyright (C) 2026 Imhotep contributors.',
             ' * Licensed under the GNU AGPL-3.0.',
             ' *',
             ' * @bin each value is the entry point of a function of Pharaoh.exe whose port lists it (the file',
             ' * after the name); the name is the port\'s. Conventions: docs/naming.md. */',
             '#ifndef IMHOTEP_STATE_FUNCTIONS_H',
             '#define IMHOTEP_STATE_FUNCTIONS_H',
             '']
    for a in sorted(found):
        n, path = found[a]
        i = ident(n)
        if len(by_name[i]) > 1:
            i = '%s_%06X' % (i, a & 0xFFFFFF)
        lines.append('#define FN_%s 0x%08Xu /* %s */' % (i, a, path))
    lines += ['', '#endif', '']
    open(os.path.join(ROOT, 'core', 'state', 'functions.h'), 'w').write('\n'.join(lines))
    print('%d functions' % len(found))
    return 0


if __name__ == '__main__':
    sys.exit(main())
