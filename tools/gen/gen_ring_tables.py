"""Write the static tile rings around 2x2 .. 6x6 footprints (dx, dy byte pairs, rings 1-6).

  python3 tools/gen/gen_ring_tables.py   # reads $IMHOTEP_GAME_DIR/Pharaoh.exe

Pharaoh.exe keeps these rings as static data (read by 0x00481AA0 and 0x00481F20); the 1x1 rings
are generated at run time (0x0046F8D0) and are computed in core/city/desirability.c. The tile
order is kept: the 6x6 edge test of 0x00481AA0 pairs ring r's tiles with ring r+1's entries.
Each ring is checked to be the square ring at Chebyshev distance r around the footprint.
"""
import hashlib, json, os, struct, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
GAME_DIR = Path(os.environ.get("IMHOTEP_GAME_DIR", ROOT / "local" / "game" / "app"))
OUT = ROOT / "core" / "city" / "ring_tables.c"

# @bin 0x00481AA0: per footprint size, the dx/dy table of rings 1..6
PAIRS = {
    2: [0x5C9BA8, 0x5C9BC0, 0x5C9BE8, 0x5C9C20, 0x5C9C68, 0x5C9CC0],
    3: [0x5C9D28, 0x5C9D48, 0x5C9D78, 0x5C9DB8, 0x5C9E08, 0x5C9E68],
    4: [0x5C9ED8, 0x5C9F00, 0x5C9F38, 0x5C9F80, 0x5C9FD8, 0x5CA040],
    5: [0x5CA0B8, 0x5CA0E8, 0x5CA128, 0x5CA178, 0x5CA1D8, 0x5CA248],
    6: [0x5CA2C8, 0x5CA300, 0x5CA348, 0x5CA3A0, 0x5CA408, 0x5CA480],
}
COUNTS = {2: 0x5C9B16, 3: 0x5C9B22, 4: 0x5C9B2E, 5: 0x5C9B3A, 6: 0x5C9B46}  # short at base + 2r


def main() -> None:
    exe = (GAME_DIR / "Pharaoh.exe").read_bytes()
    record = json.loads((ROOT / "docs" / "source-fingerprint.json").read_text())["files"]
    if hashlib.sha256(exe).hexdigest() != record.get("Pharaoh.exe"):
        sys.exit("Pharaoh.exe does not match the reference fingerprint")
    off = lambda va: va - 0x576000 + 0x176000
    L = ["/* Generated by tools/gen/gen_ring_tables.py from the reference Pharaoh.exe (GOG 2.1,",
         " * docs/source-fingerprint.json). Do not edit. Licensed under the GNU AGPL-3.0. */",
         '#include "city/ring_tables.h"', ""]
    counts = []
    for n, addrs in PAIRS.items():
        for r, a in enumerate(addrs, 1):
            cnt = struct.unpack_from("<h", exe, off(COUNTS[n] + 2 * r))[0]
            pts = [struct.unpack_from("<2b", exe, off(a) + 2 * i) for i in range(cnt)]
            exp = {(dx, dy) for dx in range(-r, n + r) for dy in range(-r, n + r)
                   if max(max(-dx, dx - (n - 1), 0), max(-dy, dy - (n - 1), 0)) == r}
            assert set(pts) == exp and len(pts) == len(exp), (n, r)
            counts.append((n, r, cnt))
            L.append(f"/* @bin 0x{a:08X} size {n} ring {r}: {cnt} tiles */")
            L.append(f"static const int8_t ring_{n}_{r}[{2 * cnt}] = {{" + ", ".join(f"{dx}, {dy}" for dx, dy in pts) + "};")
    L.append("")
    L.append("const ring_table ring_tables[7][7] = {")
    for n in range(7):
        row = []
        for r in range(7):
            if n in PAIRS and 1 <= r <= 6:
                cnt = next(c for nn, rr, c in counts if nn == n and rr == r)
                row.append(f"{{ring_{n}_{r}, {cnt}}}")
            else:
                row.append("{0, 0}")
        L.append("    {" + ", ".join(row) + "},")
    L += ["};", ""]
    OUT.write_text("\n".join(L))
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
