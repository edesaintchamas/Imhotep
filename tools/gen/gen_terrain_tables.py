"""Write the terrain neighbour-pattern tables read by Pharaoh.exe into a C source file.

  python3 tools/gen/gen_terrain_tables.py   # reads $IMHOTEP_GAME_DIR/Pharaoh.exe

The tables are game rules (neighbour patterns -> image offsets), embedded the way Julius embeds
Caesar III's image context tables, each tagged with its address in the reference binary.
Checks the executable's SHA-256 against docs/source-fingerprint.json first.
"""
import hashlib, json, os, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
GAME_DIR = Path(os.environ.get("IMHOTEP_GAME_DIR", ROOT / "local" / "game" / "app"))
OUT = ROOT / "core" / "map" / "terrain_tables.c"

# name, address, records, reader in Pharaoh.exe
TABLES = [
    ("terrain_pattern_shore", 0x005CA658, 0x30, "0x0047A220, 0x0047AB10"),
    ("terrain_pattern_deep", 0x005CBFB8, 0x1A, "0x0047A220, 0x004767D0"),
    ("terrain_pattern_floodplain", 0x005CAC58, 0x18 * 8, "0x00479E70 (8 blocks of 24, 0x00484D70)"),
    ("terrain_pattern_special_rocks", 0x005CBEA8, 0x11, "0x004798E0"),
    ("terrain_pattern_roads", 0x005CC268, 0x11, "0x0047B670"),
    ("terrain_pattern_walls", 0x005CB9D8, 0x30, "0x0047B1A0"),
    ("terrain_pattern_walls_building", 0x005CBCD8, 0x0F, "0x0047B1A0"),
    ("terrain_pattern_canals", 0x005CC678, 0x10, "0x0047BAE0, 0x0047B670"),
]


def main() -> None:
    exe_path = GAME_DIR / "Pharaoh.exe"
    exe = exe_path.read_bytes()
    record = json.loads((ROOT / "docs" / "source-fingerprint.json").read_text())["files"]
    if hashlib.sha256(exe).hexdigest() != record.get("Pharaoh.exe"):
        sys.exit("Pharaoh.exe does not match the reference fingerprint")
    lines = [
        "/* Generated by tools/gen/gen_terrain_tables.py from the reference Pharaoh.exe (GOG 2.1,",
        " * docs/source-fingerprint.json). Do not edit. Licensed under the GNU AGPL-3.0. */",
        '#include "map/terrain_tables.h"',
        "",
    ]
    for name, va, count, reader in TABLES:
        off = va - 0x576000 + 0x176000          # .data: VA 0x576000 <-> file offset 0x176000
        data = exe[off: off + 16 * count]
        lines.append(f"/* @bin 0x{va:08X} {count} records of 16 bytes, read by {reader} */")
        lines.append(f"const uint8_t {name}[{count}][16] = {{")
        for k in range(count):
            rec = ", ".join(f"{b:3d}" for b in data[16 * k: 16 * k + 16])
            lines.append(f"    {{{rec}}},")
        lines.append("};")
        lines.append("")
    OUT.write_text("\n".join(lines))
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
