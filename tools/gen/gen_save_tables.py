"""Write the static tables the saved-game loader's later steps read (docs/formats/save.md §2, §4).

  python3 tools/gen/gen_save_tables.py   # reads $IMHOTEP_GAME_DIR/Pharaoh.exe and the decompiled
                                         # 0x004212F0 in local/ghidra-export (block order)

- monument clean-up programs (0x00420D10, 0x00421010, 0x004206A0, 0x004209E0, 0x004212F0,
  obelisks 0x004E5B90): {record address, value} in execution order;
- option descriptors read by 0x0041FCA0 (0x005BE9C8 + id * 0x28, id < 0xFD): item values,
  state options; only read by the game (no writer in the decompiled code);
- the exe's initial dword 0 of the records restored by loader step 7, and the initial content
  of chunks 176-180 (what a freshly started game holds before its first load);
- event flags 0x005D9C78 (0x004493C0), default prices 0x005D2E60 (0x004D40C0), pyramid tables
  0x0056F7D8 / 0x0056F7EC (0x004D3DA0): 256 entries each, i.e. every index a byte can take.
"""
import hashlib, json, os, re, struct, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
GAME_DIR = Path(os.environ.get("IMHOTEP_GAME_DIR", ROOT / "local" / "game" / "app"))
EXPORT = ROOT / "local" / "ghidra-export" / "functions"
OUT = ROOT / "core" / "io" / "save_tables.c"


def main() -> None:
    exe = (GAME_DIR / "Pharaoh.exe").read_bytes()
    record = json.loads((ROOT / "docs" / "source-fingerprint.json").read_text())["files"]
    if hashlib.sha256(exe).hexdigest() != record.get("Pharaoh.exe"):
        sys.exit("Pharaoh.exe does not match the reference fingerprint")

    def off(va):
        if 0x576000 <= va < 0x606000:
            return va - 0x576000 + 0x176000
        if 0x56F000 <= va < 0x576000:
            return va - 0x56F000 + 0x16F000
        raise ValueError(hex(va))

    i32 = lambda va: struct.unpack_from("<i", exe, off(va))[0]
    u32 = lambda va: struct.unpack_from("<I", exe, off(va))[0]

    def block(start, end, values=None):
        """16-byte entries {record pointer, value, ...} from start to end (exclusive)."""
        out = []
        for k, e in enumerate(range(start, end, 16)):
            out.append((u32(e), i32(values + 16 * k) if values else i32(e + 4)))
        return out

    # 0x004212F0: blocks in code order; one block takes its values from another table
    tomb_src = json.loads((EXPORT / "0x004212F0.json").read_text())["decompiled"]
    tombs = []
    for m in re.finditer(r"ppuVar5 = &PTR_DAT_([0-9a-f]+);.*?while \(\(int\)ppuVar5 < 0x([0-9a-f]+)\)|"
                         r"\(int\)&PTR_DAT_([0-9a-f]+) \+ iVar6\) \+ 0x12\).*?&DAT_([0-9a-f]+) \+ iVar6\);.*?"
                         r"while \(iVar6 < 0x([0-9a-f]+)\)", tomb_src, re.S):
        if m.group(1):
            tombs += block(int(m.group(1), 16), int(m.group(2), 16))
        else:
            s = int(m.group(3), 16)
            tombs += block(s, s + int(m.group(5), 16), values=int(m.group(4), 16))
    programs = {
        "caesareum": block(0x005AD218, 0x005AD3C8),      # @bin 0x00420D10
        "pharos": block(0x005B0060, 0x005B0150),         # @bin 0x00421010
        "library": block(0x0059EDF0, 0x0059EFA0),        # @bin 0x004206A0
        "abu_simbel": block(0x005A8148, 0x005A84C8),     # @bin 0x004209E0
        "tombs": tombs,                                  # @bin 0x004212F0
        # @bin 0x004E5B90 reads {record, value} at +8/+0xC of each 16-byte entry (0x004E5BD5)
        "obelisk_small": block(0x00586B08 + 8, 0x00586B08 + 8 + 16 * 10),   # type 0xCF
        "obelisk_large": block(0x0058FE48 + 8, 0x0058FE48 + 8 + 16 * 18),   # type 0xD0
    }
    assert len(tombs) == 75, len(tombs)

    # 0x0041FCA0 descriptors
    desc, states, items = [], [], []
    for k in range(0xFD):
        base = 0x005BE9C8 + 0x28 * k
        iptr, icount, sptr, scount = u32(base), i32(base + 4), u32(base + 8), i32(base + 12)
        desc.append((len(states) // 10, max(scount, 0), len(items), max(icount, 0)))
        for s in range(max(scount, 0)):
            states += [i32(sptr + 40 * s + 4 * j) for j in range(10)]
        for it in range(max(icount, 0)):
            items.append(i32(iptr + 0x30 * it + 0xC))

    restore = {
        "chunk171": (0x005E45B0, 10), "chunk172": (0x005E46A0, 18),
        "chunk146": (0x005C1140, 22), "chunk149": (0x005C1350, 13),
    }
    initial = [(a, n) for a, n in ((0x005C1F80, 27), (0x005C1488, 27), (0x005C1E18, 15),
                                   (0x005C2208, 56), (0x005C1710, 75))]

    L = ["/* Generated by tools/gen/gen_save_tables.py from the reference Pharaoh.exe (GOG 2.1,",
         " * docs/source-fingerprint.json). Do not edit. Licensed under the GNU AGPL-3.0. */",
         '#include "io/save_tables.h"', ""]
    for name, prog in programs.items():
        L.append(f"const save_cleanup_entry save_cleanup_{name}[] = {{")
        L += [f"    {{0x{a:08X}u, {v}}}," for a, v in prog]
        L += ["};", f"const int save_cleanup_{name}_count = {len(prog)};", ""]
    L.append("/* @bin 0x005BE9C8 + id * 0x28: {first state, states, first item, items} */")
    L.append("const save_option_desc save_option_descs[SAVE_OPTION_DESCS] = {")
    L += [f"    {{{a}, {b}, {c}, {d}}}," for a, b, c, d in desc]
    L += ["};", "const int32_t save_option_states[] = {"]
    for s in range(0, len(states), 10):
        L.append("    " + ", ".join(str(x) for x in states[s:s + 10]) + ",")
    L += ["};", "const int32_t save_option_items[] = {"]
    for s in range(0, len(items), 12):
        L.append("    " + ", ".join(str(x) for x in items[s:s + 12]) + ",")
    L += ["};", ""]
    for name, (a, n) in restore.items():
        L.append(f"/* @bin 0x{a:08X}: initial dword 0 of each 24-byte record */")
        L.append(f"const int32_t save_restore_{name}[{n}] = {{{', '.join(str(i32(a + 24 * r)) for r in range(n))}}};")
    L.append("")
    L.append("/* initial content of chunks 176-180 (0x005C1F80, 0x005C1488, 0x005C1E18, 0x005C2208, 0x005C1710) */")
    for idx, (a, n) in zip(range(176, 181), initial):
        raw = exe[off(a):off(a) + 24 * n]
        L.append(f"const uint8_t save_initial_chunk{idx}[{24 * n}] = {{")
        for s in range(0, len(raw), 24):
            L.append("    " + ", ".join(str(b) for b in raw[s:s + 24]) + ",")
        L.append("};")
    L.append("")
    L.append("/* @bin 0x005D9C78 event-type flags read by 0x004493C0 (any byte index) */")
    L.append("const uint8_t save_event_flags[256] = {" + ", ".join(str(b) for b in exe[off(0x005D9C78):off(0x005D9C78) + 256]) + "};")
    L.append("/* @bin 0x005D2E60 the 5 price pairs 0x004D40C0 copies to 0x005D2D40 */")
    L.append("const int32_t save_default_prices[10] = {" + ", ".join(str(i32(0x005D2E60 + 4 * k)) for k in range(10)) + "};")
    for name, a in (("pyramid_slots", 0x0056F7D8), ("pyramid_slots_kind5", 0x0056F7EC)):
        L.append(f"/* @bin 0x{a:08X} read by 0x004D3DA0 with a byte index */")
        L.append(f"const int32_t save_{name}[256] = {{" + ", ".join(str(i32(a + 4 * k)) for k in range(256)) + "};")
    L.append("")
    OUT.write_text("\n".join(L))
    print(f"wrote {OUT.relative_to(ROOT)}: {len(states)//10} states, {len(items)} items, "
          f"{sum(map(len, programs.values()))} clean-up entries")


if __name__ == "__main__":
    main()
